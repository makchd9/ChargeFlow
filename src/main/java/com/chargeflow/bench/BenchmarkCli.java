package com.chargeflow.bench;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Runs the full benchmark suite and writes benchmarks/results.csv and benchmarks/results.md.
 * Usage: ./mvnw -q compile exec:java      (or: ./mvnw -q compile exec:java -Dexec.args="quick")
 */
public final class BenchmarkCli {

    public static void main(String[] args) throws IOException {
        boolean quick = args.length > 0 && args[0].equalsIgnoreCase("quick");
        int reps = quick ? 3 : 5;
        List<Benchmarks.Row> rows = new ArrayList<>();

        System.out.println("== max-flow allocation ==");
        rows.addAll(print(Benchmarks.flow(quick ? new int[]{250, 1000, 2000} : new int[]{250, 1000, 2000, 4000}, reps)));
        rows.addAll(print(Benchmarks.flowDeepRandom(quick ? new int[]{500, 1000, 2000} : new int[]{500, 1000, 2000, 4000}, reps)));
        System.out.println("== selection ==");
        rows.addAll(print(Benchmarks.selection(
                quick ? new int[]{10_000, 100_000, 1_000_000} : new int[]{10_000, 100_000, 1_000_000, 4_000_000},
                quick ? new int[]{5_000, 10_000, 20_000} : new int[]{5_000, 10_000, 20_000, 40_000}, reps)));
        System.out.println("== bloom filter ==");
        rows.addAll(print(Benchmarks.bloom(quick ? new int[]{10_000, 100_000, 500_000} : new int[]{10_000, 100_000, 1_000_000}, 0.01, 100_000)));
        rows.addAll(print(Benchmarks.bloomFprSweep(100_000, new double[]{0.1, 0.05, 0.01, 0.001}, 200_000)));

        Path dir = Path.of("benchmarks");
        Files.createDirectories(dir);
        StringBuilder csv = new StringBuilder("experiment,variant,n,median_ms,work,quality,note\n");
        StringBuilder md = new StringBuilder("# Benchmark results\n\n")
                .append("Generated by `BenchmarkCli` (").append(quick ? "quick" : "full").append(" mode). JVM: ")
                .append(System.getProperty("java.version")).append(", ").append(System.getProperty("os.arch"))
                .append(", ").append(Runtime.getRuntime().availableProcessors()).append(" cores.\n")
                .append("Median of ").append(reps).append(" timed runs after 2 warm-ups. `work` = arc scans (flow), comparisons (selection), bits/probes (Bloom).\n\n")
                .append("| experiment | variant | n | median ms | work | quality | note |\n|---|---|---:|---:|---:|---:|---|\n");
        for (Benchmarks.Row r : rows) {
            csv.append(String.format(Locale.ROOT, "%s,%s,%d,%.3f,%.0f,%.6f,\"%s\"%n", r.experiment(), r.variant(), r.n(), r.medianMs(), r.work(), r.quality(), r.note()));
            md.append(String.format(Locale.ROOT, "| %s | %s | %,d | %.3f | %,.0f | %s | %s |%n", r.experiment(), r.variant(), r.n(), r.medianMs(), r.work(),
                    r.quality() == Math.rint(r.quality()) ? String.format(Locale.ROOT, "%,.0f", r.quality()) : String.format(Locale.ROOT, "%.5f", r.quality()), r.note()));
        }
        Files.writeString(dir.resolve("results.csv"), csv.toString());
        Files.writeString(dir.resolve("results.md"), md.toString());
        System.out.println("wrote " + dir.resolve("results.csv") + " and results.md");
    }

    private static List<Benchmarks.Row> print(List<Benchmarks.Row> rows) {
        for (Benchmarks.Row r : rows)
            System.out.printf(Locale.ROOT, "%-26s %-36s n=%-9d %10.3f ms  work=%-14.0f quality=%-12.5f %s%n",
                    r.experiment(), r.variant(), r.n(), r.medianMs(), r.work(), r.quality(), r.note());
        return rows;
    }
}
